        <!-- COLUMNA DERECHA: CARRUSEL STICKY CON AUTOPLAY -->
        <div class="w-full sm:sticky sm:top-8 mt-[4vw] sm:mt-0">
          <!-- 🔥 Eventos @mouseenter y @mouseleave para pausar/reanudar autoplay -->
          <div 
            class="relative w-full bg-gray-100 rounded-xl overflow-hidden shadow-lg aspect-[4/3] |sm:aspect-square lg:aspect-[4/5] mt-[0vw] sm:mt-[3vw] group"
            @mouseenter="stopAutoplay"
            @mouseleave="startAutoplay"
          >
            
            <!-- Transición de Vue para el carrusel -->
            <Transition name="fade" mode="out-in">
              <div :key="currentImageIndex" class="absolute inset-0 flex items-center justify-center p-2 cursor-pointer" @click="abrirPantallaCompleta">
