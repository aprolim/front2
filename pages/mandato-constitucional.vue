            @click.stop="toggleZoom"
          >
            <img
              :src="imagenesCarrusel[currentImageIndex].src"
              :alt="imagenesCarrusel[currentImageIndex].alt"
              :class="[
                'rounded-lg shadow-2xl transition-all duration-300 origin-center',
                isZoomed ? 'max-w-none w-[150vw] sm:w-[120vw] cursor-zoom-out' : 'max-w-full max-h-full cursor-zoom-in object-contain'
              ]"
            />
          </div>
          
          <!-- Indicadores de texto -->
          <div class="absolute bottom-4 left-1/2 -translate-x-1/2 text-white/50 text-sm hidden sm:block">
            {{ currentImageIndex + 1 }} / {{ imagenesCarrusel.length }} (Usa las flechas del teclado o haz clic en la imagen para zoom)
          </div>
        </div>
      </Transition>
    </Teleport>
  </div>
