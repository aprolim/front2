<script setup>
import { ref, onMounted, onUnmounted } from 'vue'

// Configuración del carrusel
const currentImageIndex = ref(0)
const isFullScreen = ref(false)
const isZoomed = ref(false)

const imagenesCarrusel = [
  {
    src: '/Mandato Constitucional Senado/15.png',
    alt: 'Mandato Constitucional Senado - Imagen 15',
    isPortrait: false
  },
  {
    src: '/Mandato Constitucional Senado/27.JPG',
    alt: 'Mandato Constitucional Senado - Imagen 27',
    isPortrait: false
  },
  {
    src: '/Mandato Constitucional Senado/6.png',
    alt: 'Mandato Constitucional Senado - Imagen 6',
    isPortrait: true
  }
]

// --- LÓGICA DE AUTOPLAY ---
let slideInterval = null
const autoplayDelay = 5000 // 5 segundos

const startAutoplay = () => {
  stopAutoplay() // Evitar duplicados
  // Solo avanza si no está en pantalla completa (para no molestar el zoom)
  slideInterval = setInterval(() => {
    if (!isFullScreen.value) {
      nextImage()
    }
  }, autoplayDelay)
}

const stopAutoplay = () => {
  if (slideInterval) {
    clearInterval(slideInterval)
    slideInterval = null
  }
}

const restartAutoplay = () => {
  startAutoplay() // Al interactuar manualmente, reiniciamos el contador a 5s
}
// -------------------------

const nextImage = () => {
  currentImageIndex.value = (currentImageIndex.value + 1) % imagenesCarrusel.length
  if (isZoomed.value) isZoomed.value = false // Resetear zoom al cambiar de imagen
}

const prevImage = () => {
  currentImageIndex.value = (currentImageIndex.value - 1 + imagenesCarrusel.length) % imagenesCarrusel.length
  if (isZoomed.value) isZoomed.value = false // Resetear zoom al cambiar de imagen
}

// Funciones para pantalla completa
const abrirPantallaCompleta = () => {
  isFullScreen.value = true
  isZoomed.value = false
  if (process.client) document.body.style.overflow = 'hidden'
  stopAutoplay() // Pausamos el autoplay al abrir pantalla completa
}

const cerrarPantallaCompleta = () => {
  isFullScreen.value = false
  isZoomed.value = false
  if (process.client) document.body.style.overflow = 'auto'
  startAutoplay() // Reanudamos al cerrar
}

// Alternar Zoom
const toggleZoom = (e) => {
  e.stopPropagation() 
  isZoomed.value = !isZoomed.value
}

// Lógica para detectar teclas (Escape, Flecha Izquierda, Flecha Derecha)
const handleKeydown = (e) => {
  if (e.key === 'Escape' || e.keyCode === 27) {
    if (isFullScreen.value) cerrarPantallaCompleta()
  } else if (e.key === 'ArrowRight' || e.keyCode === 39) {
    nextImage()
    restartAutoplay()
  } else if (e.key === 'ArrowLeft' || e.keyCode === 37) {
    prevImage()
    restartAutoplay()
  }
}

onMounted(() => {
  if (process.client) {
    window.addEventListener('keydown', handleKeydown)
    startAutoplay() // 🔥 Iniciar el carrusel automático al montar el componente
  }
})

onUnmounted(() => {
  if (process.client) {
    window.removeEventListener('keydown', handleKeydown)
    stopAutoplay() // Limpiar el temporizador
  }
})
</script>

